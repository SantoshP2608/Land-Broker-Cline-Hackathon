import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { chromium } from 'playwright';

const server = await createServer({ server: { host: '127.0.0.1', port: 5181, strictPort: true } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--disable-extensions'] });
  const page = await browser.newPage();
  page.setDefaultTimeout(10000);
  page.setDefaultNavigationTimeout(30000);
  const errors = [];
  const apiRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) apiRequests.push(request.url()); });
  await mkdir(new URL('../artifacts/', import.meta.url), { recursive: true });
  const goto = path => page.goto(`http://127.0.0.1:5181${path}`);
  for (const width of [1600, 1280, 1024, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    for (const [number, title, ready] of [[12, 'Agreement & Registration Preparation', 'Submit for Registration'], [13, 'Cancellation / Hold & Resolution', 'Upload Additional Evidence']]) {
      await goto(`/page-${number}`);
      await page.getByRole('heading', { name: title, exact: true }).waitFor();
      await page.getByRole('button', { name: ready, exact: true }).waitFor();
      await page.evaluate(async () => { await document.fonts.ready; await Promise.all([...document.images].map(image => image.decode().catch(() => {}))); });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Page ${number} overflow at ${width}`);
      assert.equal(await page.locator('img').evaluateAll(images => images.filter(image => !image.naturalWidth).length), 0);
      if ([1600, 390, 320].includes(width)) await page.screenshot({ path: fileURLToPath(new URL(`../artifacts/page-${number}-${width}.png`, import.meta.url)), fullPage: true });
      console.log(`PASS page ${number}, ${width}px: no horizontal overflow, images loaded`);
    }
  }
  await page.setViewportSize({ width: 1600, height: 1000 });
  await goto('/page-12');
  await page.getByRole('button', { name: 'Submit for Registration', exact: true }).waitFor();
  await page.getByRole('button', { name: /draft.*page 2|page 2.*draft/i }).click();
  await page.getByRole('heading', { name: 'TERMS OF SALE', exact: true }).waitFor();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PDF', exact: true }).click();
  const download = await downloadEvent;
  assert.match(download.suggestedFilename(), /\.pdf$/);
  assert.match((await readFile(await download.path())).toString(), /^%PDF-1\.4/);
  await page.getByRole('tab', { name: 'Draft Agreement' }).focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.getByRole('tab', { name: 'Terms & Conditions' }).getAttribute('aria-selected'), 'true');
  await page.getByRole('tab', { name: 'Draft Agreement' }).click();
  await page.getByRole('button', { name: 'Open fullscreen draft deed', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'visible' });
  assert.equal(await page.getByRole('dialog').locator('article').count(), 3);
  await page.emulateMedia({ media: 'print' });
  const printed = await page.pdf({ path: fileURLToPath(new URL('../artifacts/transaction-print-check.pdf', import.meta.url)), format: 'A4' });
  assert.match(printed.toString(), /^%PDF-/);
  await page.emulateMedia({ media: 'screen' });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'View Guide', exact: true }).click();
  await page.getByRole('heading', { name: 'Agreement & registration guide', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Submit for Registration', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'visible' });
  assert.equal(await page.getByRole('button', { name: 'Confirm registration submission' }).isDisabled(), true);
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Confirm registration submission' }).click();
  await page.getByRole('button', { name: 'Application Submitted', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Application Submitted', exact: true }).isDisabled(), true);
  console.log('PASS page 12: draft selection, valid PDF download, keyboard tabs, registration consent/pending state');

  await goto('/page-12');
  await page.getByRole('button', { name: 'Edit agreed terms', exact: true }).click();
  await page.getByLabel('Price per acre (INR)', { exact: true }).fill('4600000');
  await page.getByRole('button', { name: 'Save terms', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm as Buyer', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Submit for Registration', exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: 'Confirm as Buyer', exact: true }).click();
  await page.getByRole('status').filter({ hasText: /Buyer confirmation recorded/ }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Submit for Registration', exact: true }).isDisabled(), true);
  console.log('PASS page 12: editing invalidates both confirmations; buyer cannot confirm for seller');

  await goto('/page-13');
  await page.getByRole('button', { name: 'View Supporting Evidence (3 files)', exact: true }).click();
  await page.getByRole('heading', { name: 'Encumbrance discrepancy.pdf', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'View Response & Evidence (2 files)', exact: true }).click();
  await page.getByRole('heading', { name: 'Seller response.pdf', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'View synthetic Survey map', exact: true }).click();
  await page.getByRole('heading', { name: 'Survey map', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'View Guide', exact: true }).click();
  await page.getByRole('heading', { name: 'Cancellation & Resolution Guide', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Send a Message', exact: true }).click();
  await page.getByLabel('Message to the other party').fill('Synthetic request for clarification.');
  await page.getByRole('button', { name: 'Send Message Locally', exact: true }).click();
  await page.getByRole('status').filter({ hasText: /message/i }).waitFor();
  const visibleDialog = page.getByRole('dialog');
  if (await visibleDialog.isVisible()) await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Upload Additional Evidence', exact: true }).click();
  await page.getByLabel('Additional evidence files', { exact: true }).setInputFiles({ name: 'bad.exe', mimeType: 'application/octet-stream', buffer: Buffer.from('bad') });
  assert.equal(await page.getByRole('button', { name: 'Review Selected Files', exact: true }).isDisabled(), true);
  await page.getByLabel('Additional evidence files', { exact: true }).setInputFiles({ name: 'synthetic.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4 synthetic') });
  await page.getByRole('button', { name: 'Review Selected Files', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm Local Evidence Upload', exact: true }).click();
  await page.getByRole('button', { name: 'View Supporting Evidence (4 files)', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Withdraw Cancellation Request', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm Withdrawal Request', exact: true }).click();
  await page.getByRole('status').filter({ hasText: /withdrawal/i }).waitFor();
  assert.match(await page.locator('.cancellation-page').textContent(), /authority.*pending|pending.*authority/i);
  console.log('PASS page 13: evidence preview, local message, file rejection/staging, pending withdrawal request');
  await page.setViewportSize({ width: 390, height: 900 });
  await page.getByRole('button', { name: 'Toggle transaction navigation' }).click();
  assert.equal(await page.getByRole('button', { name: 'Toggle transaction navigation' }).getAttribute('aria-expanded'), 'true');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button', { name: 'Toggle transaction navigation' }).getAttribute('aria-expanded'), 'false');
  await page.getByRole('button', { name: 'Back to Transaction', exact: true }).click();
  await page.getByRole('heading', { name: 'Transaction previews', exact: true }).waitFor();
  assert.deepEqual(errors, []);
  assert.deepEqual(apiRequests, []);
  console.log('PASS enlarged/printable HTML deed, guides, seller response and document dialogs');
  console.log('PASS mobile navigation/back route; no browser runtime errors or API calls');
} finally {
  await browser?.close();
  await server.close();
}